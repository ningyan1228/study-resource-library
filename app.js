function initAmbientBackgroundVideo() {
  const video = document.querySelector("#ambientBackgroundVideo");
  const canvas = document.querySelector("#ambientBackgroundCanvas");
  if (!video || !canvas) return;

  const isTouchDevice = window.matchMedia("(hover: none), (pointer: coarse)").matches
    || navigator.maxTouchPoints > 0;
  const disableForPreference = window.matchMedia("(prefers-reduced-motion: reduce)").matches
    || window.matchMedia("(prefers-reduced-data: reduce)").matches;
  if (disableForPreference) {
    video.remove();
    canvas.remove();
    return;
  }

  // Touch browsers should never initialise a native video or Canvas decoder.
  // The compact animated WebP is loaded only by the background element's CSS.
  if (isTouchDevice) {
    video.remove();
    canvas.remove();
    document.body.classList.add("has-animated-background");
    return;
  }

  const source = video.querySelector("source[data-src]");
  const context = canvas.getContext("2d", { alpha: true });
  if (!source || !context) return;

  const connection = navigator.connection || navigator.mozConnection || navigator.webkitConnection;
  const constrainedNetwork = connection?.saveData || /(^|-)2g/.test(connection?.effectiveType || "");
  if (constrainedNetwork) {
    video.remove();
    canvas.remove();
    return;
  }
  video.muted = true;
  video.defaultMuted = true;
  video.setAttribute("muted", "");
  video.setAttribute("playsinline", "");
  video.setAttribute("webkit-playsinline", "");
  let videoSourceLoaded = false;
  const loadVideoSource = () => {
    if (videoSourceLoaded) return;
    videoSourceLoaded = true;
    source.src = source.dataset.src;
    video.load();
  };

  let frameId = 0;
  let lastFrameAt = 0;
  let hasPaintedFrame = false;
  let startButton = null;
  const resizeCanvas = () => {
    const density = Math.min(window.devicePixelRatio || 1, 1.35);
    canvas.width = Math.max(1, Math.round(window.innerWidth * density));
    canvas.height = Math.max(1, Math.round(window.innerHeight * density));
  };

  const paintFrame = (now) => {
    if (now - lastFrameAt >= 83 && video.readyState >= HTMLMediaElement.HAVE_CURRENT_DATA && video.videoWidth && video.videoHeight) {
      const canvasRatio = canvas.width / canvas.height;
      const videoRatio = video.videoWidth / video.videoHeight;
      let sourceX = 0;
      let sourceY = 0;
      let sourceWidth = video.videoWidth;
      let sourceHeight = video.videoHeight;

      if (videoRatio > canvasRatio) {
        sourceWidth = Math.round(video.videoHeight * canvasRatio);
        sourceX = Math.round((video.videoWidth - sourceWidth) / 2);
      } else {
        sourceHeight = Math.round(video.videoWidth / canvasRatio);
        sourceY = Math.round((video.videoHeight - sourceHeight) / 2);
      }

      context.drawImage(video, sourceX, sourceY, sourceWidth, sourceHeight, 0, 0, canvas.width, canvas.height);
      if (!hasPaintedFrame) {
        hasPaintedFrame = true;
        document.body.classList.remove("has-animated-background");
        document.body.classList.add("has-ambient-video");
        hideStartButton();
      }
      lastFrameAt = now;
    }
    frameId = window.requestAnimationFrame(paintFrame);
  };

  const hideStartButton = () => {
    startButton?.remove();
    startButton = null;
  };

  const activateVideo = () => {
    if (!videoSourceLoaded) return;
    resizeCanvas();
    video.play()
      .then(() => {
        if (!frameId) frameId = window.requestAnimationFrame(paintFrame);
      })
      .catch(() => {
        document.body.classList.remove("has-ambient-video");
        showStartButton();
      });
  };

  const showStartButton = () => {
    if (startButton || document.body.classList.contains("has-ambient-video")) return;
    startButton = document.createElement("button");
    startButton.type = "button";
    startButton.className = "ambient-video-toggle";
    startButton.innerHTML = '<span aria-hidden="true">▶</span> 开启动态背景';
    startButton.addEventListener("click", activateVideo);
    document.body.append(startButton);
    document.body.classList.add("ambient-video-needs-start");
  };

  window.addEventListener("resize", resizeCanvas, { passive: true });
  document.addEventListener("visibilitychange", () => {
    if (document.hidden) {
      video.pause();
      return;
    }
    activateVideo();
  });
  video.addEventListener("error", () => {
    window.cancelAnimationFrame(frameId);
    document.body.classList.remove("has-ambient-video");
  }, { once: true });
  video.addEventListener("canplay", activateVideo, { once: true });
  // The 22 MB desktop clip is decorative. Do not compete with the first page
  // render; begin it only after a visible, idle page has had time to settle.
  scheduleNonCriticalTask(() => {
    if (!document.hidden) loadVideoSource();
  }, 4000);
}
