function getVisitorId() {
  try {
    const key = "study-resource-visitor-id";
    let id = localStorage.getItem(key);
    if (!id) { id = crypto.randomUUID ? crypto.randomUUID() : `${Date.now()}-${Math.random()}`; localStorage.setItem(key, id); }
    return id;
  } catch (_) { return ""; }
}
sendServerEvent("site_view", { visitorId: getVisitorId() });
function sendServerEvent(type, payload = {}) {
  if (!serverApiBase || !type) return false;

  const body = JSON.stringify({
    type,
    payload,
    page: window.location.href,
    referrer: document.referrer || "",
    userAgent: navigator.userAgent,
    ts: Date.now()
  });

  try {
    fetch(`${serverApiBase}/api/events`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body,
      keepalive: body.length < 60000
    }).catch(() => {});
    return true;
  } catch (_) {
    return false;
  }
}

// Site-wide anonymous presence is intentionally separate from the study-room seats.
// A browser sends only its existing random visitor id; the server keeps it in memory
// briefly and never writes this presence list to disk.
function startSitePresence() {
  const online = document.querySelector("#siteGlobalOnline");
  const visitorId = getVisitorId();
  if (!online || !serverApiBase || !visitorId) return;

  const render = (data) => {
    const count = Math.max(0, Number(data?.onlineCount || 0));
    online.textContent = `${count} 人在线`;
  };

  const refresh = async () => {
    try {
      const response = await fetch(`${serverApiBase}/api/site-presence`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ visitorId }),
        cache: "no-store",
        keepalive: true
      });
      const data = await response.json();
      if (response.ok && data?.ok) render(data);
    } catch (_) {
      // Keep the last successful count if the API is temporarily unavailable.
    }
  };

  refresh();
  window.setInterval(() => { if (!document.hidden) refresh(); }, 25000);
  document.addEventListener("visibilitychange", () => { if (!document.hidden) refresh(); });
}

function getPanSearchStats(keyword) {
  const queryTokens = panSearchTokens(keyword);
  if (!queryTokens.length) {
    return { matched: 0, quark: 0, baidu: 0, noResult: false };
  }

  const matched = panSearchData.items.filter((item) => panSearchItemMatches(item, queryTokens));
  return {
    matched: matched.length,
    quark: matched.filter((item) => item.platform === "quark").length,
    baidu: matched.filter((item) => item.platform === "baidu").length,
    noResult: matched.length === 0
  };
}

