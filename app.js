// Names from different sources often add platform-specific decorations. Keep this list
// deliberately small so the fallback connects the same course without broadening search too much.
const PAN_SEARCH_DECORATION_WORDS = /(?:国省考季|国省考|公考|网盘资料|网课资料|课程资料|资料合集|课程合集|全套资料)/g;

function panSearchNormalize(text) {
  return String(text || "")
    .toLocaleLowerCase("zh-CN")
    .replace(/\s+/g, " ")
    .trim();
}

function panSearchCompact(text) {
  return panSearchNormalize(text)
    .replace(/[“”"'‘’`·•_—－-]/g, "")
    .replace(/\s+/g, "");
}

function panSearchCoreNormalize(text) {
  return panSearchCompact(text).replace(PAN_SEARCH_DECORATION_WORDS, "");
}

function panSearchTokens(query) {
  return panSearchNormalize(query).split(/\s+/).filter(Boolean);
}

function panSearchEscapeHtml(text) {
  return String(text || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

function panSearchEscapeRegExp(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function panSearchHighlight(text, queryTokens) {
  let escaped = panSearchEscapeHtml(text);
  for (const token of queryTokens) {
    const safe = panSearchEscapeRegExp(panSearchEscapeHtml(token));
    escaped = escaped.replace(new RegExp(safe, "gi"), (match) => `<mark>${match}</mark>`);
  }
  return escaped;
}

function panSearchSourceName(item) {
  const first = item.sources && item.sources[0];
  if (!first) return "未知来源";
  return item.sources.length > 1 ? `${first.file} 等 ${item.sources.length} 处` : `${first.file}:${first.line}`;
}

function panSearchItemSearchText(item) {
  return panSearchNormalize([item.title, item.context, item.section, item.searchText, item.url].join(" "));
}

function panSearchMatchScore(item, queryTokens) {
  if (!queryTokens.length) return 0;
  const query = panSearchNormalize(queryTokens.join(" "));
  const title = panSearchNormalize(item.title);
  const haystack = panSearchItemSearchText(item);
  const directTokenMatch = queryTokens.every((token) => haystack.includes(token));
  if (query && title.includes(query)) return 120;
  if (query && haystack.includes(query)) return 110;

  // Second pass: compare course cores after removing only known listing decorations.
  const coreQuery = panSearchCoreNormalize(query);
  const coreTitle = panSearchCoreNormalize(item.title);
  const coreHaystack = panSearchCoreNormalize([item.title, item.context, item.section, item.searchText].join(" "));
  if (coreQuery && coreTitle.includes(coreQuery)) return 100;
  if (coreQuery && coreHaystack.includes(coreQuery)) return 90;
  return directTokenMatch ? 80 : 0;
}

function panSearchItemMatches(item, queryTokens) {
  return panSearchMatchScore(item, queryTokens) > 0;
}

function refreshPanSearchTotals() {
  panSearchData.totals = panSearchData.totals || {};
  panSearchData.totals.unique = panSearchData.totals.unique || {};
  panSearchData.totals.unique.total = panSearchData.items.length;
  panSearchData.totals.unique.quark = panSearchData.items.filter((item) => item.platform === "quark").length;
  panSearchData.totals.unique.baidu = panSearchData.items.filter((item) => item.platform === "baidu").length;
}

async function loadLinkHealth() {
  if (!serverApiBase || linkHealthLoaded) return;
  linkHealthLoaded = true;
  try {
    const response = await fetch(`${serverApiBase}/api/link-health`, {
      headers: { Accept: "application/json" }
    });
    if (!response.ok) return;
    const data = await response.json();
    hiddenPanUrls = new Set(Array.isArray(data.hiddenUrls) ? data.hiddenUrls : []);
    if (!hiddenPanUrls.size) return;
    panSearchData.items = panSearchData.items.filter((item) => !hiddenPanUrls.has(item?.url));
    serverPanLinks = serverPanLinks.filter((item) => !hiddenPanUrls.has(item?.url));
    refreshPanSearchTotals();
    renderSearchSuggestions();
    if (state.query.trim()) renderPanSearchResults();
  } catch (_) {
    // Keep search usable when the health service is temporarily unavailable.
  }
}
async function loadServerPanLinks() {
  if (!serverApiBase || serverPanLinksLoaded) return;
  serverPanLinksLoaded = true;

  try {
    const response = await fetch(`${serverApiBase}/api/pan-links`, {
      headers: { Accept: "application/json" }
    });
    if (!response.ok) return;

    const data = await response.json();
    const items = Array.isArray(data.items) ? data.items : [];
    serverPanLinks = items;
    if (!state.query.trim() && state.category === "all") renderResources();
    if (!items.length) return;

    const existingUrls = new Set(panSearchData.items.map((item) => item.url));
    let added = 0;

    items.forEach((item) => {
      if (!item || !item.url || hiddenPanUrls.has(item.url) || existingUrls.has(item.url)) return;
      const platform = item.platform === "baidu" ? "baidu" : "quark";
      const title = item.title || "未命名资料";
      const section = item.section || "后台新增";
      const context = item.context || title;

      panSearchData.items.unshift({
        title,
        url: item.url,
        platform,
        section,
        context,
        code: item.code || "",
        searchText: item.searchText || [title, section, context, item.code || "", platform].filter(Boolean).join(" "),
        sources: item.sources || [{ file: "server-admin", line: 1 }],
        createdAt: item.createdAt || item.updatedAt || ""
      });
      existingUrls.add(item.url);
      added += 1;
    });

    if (!added) return;
    panSearchData.totals = panSearchData.totals || {};
    panSearchData.totals.unique = panSearchData.totals.unique || {};
    panSearchData.totals.unique.total = panSearchData.items.length;
    panSearchData.totals.unique.quark = panSearchData.items.filter((item) => item.platform === "quark").length;
    panSearchData.totals.unique.baidu = panSearchData.items.filter((item) => item.platform === "baidu").length;

    renderSearchSuggestions();
    if (state.query.trim()) renderPanSearchResults();
  } catch (_) {
    // The static site should still work when the small API is temporarily unavailable.
  }
}
function renderPanSearchResults() {
  const container = document.querySelector("#panSearchResults");
  if (!container) return;

  const queryTokens = panSearchTokens(state.query);
  if (!queryTokens.length) {
    container.hidden = true;
    container.innerHTML = "";
    return;
  }

  const matched = panSearchData.items.filter((item) => panSearchItemMatches(item, queryTokens)).slice(0, 80);
  const quark = matched.filter((item) => item.platform === "quark");
  const baidu = matched.filter((item) => item.platform === "baidu");
  const totals = panSearchData.totals?.unique || {};

  container.hidden = false;
  container.innerHTML = `
    <header class="pan-search-header">
      <div>
        <span class="panel-label">网盘搜索</span>
        <h2>“${panSearchEscapeHtml(state.query)}” 的网盘资源</h2>
        <p>共匹配 ${matched.length} 条，夸克 ${quark.length} 条，百度 ${baidu.length} 条。索引库约 ${totals.total || panSearchData.items.length} 条链接。</p>
      </div>
      <button class="pan-clear-button" type="button">清空搜索</button>
    </header>
    <div class="pan-result-grid">
      ${renderPanSearchColumn("夸克网盘", quark, queryTokens)}
      ${renderPanSearchColumn("百度网盘", baidu, queryTokens)}
    </div>
  `;

  container.querySelector(".pan-clear-button").addEventListener("click", () => {
    const input = document.querySelector("#searchInput");
    state.query = "";
    input.value = "";
    renderResources();
    renderPanSearchResults();
  });

  container.querySelectorAll("[data-copy-url]").forEach((button) => {
    button.addEventListener("click", async () => {
      const copied = await copyPanSearchText(button.dataset.copyUrl);
      sendServerEvent("copy_link", { url: button.dataset.copyUrl, query: state.query.trim() });
      button.textContent = copied ? "已复制" : "手动复制";
      window.setTimeout(() => {
        button.textContent = "复制";
      }, 1300);
    });
  });

  container.querySelectorAll("[data-report-broken]").forEach((button) => {
    button.addEventListener("click", () => {
      const payload = {
        title: button.dataset.reportTitle || "",
        url: button.dataset.reportBroken || "",
        platform: button.dataset.reportPlatform || "",
        query: state.query.trim()
      };
      sendServerEvent("broken_link", payload);
      trackBaiduEvent("resource_feedback", "broken_link", payload.title || payload.url);
      showSiteToast("已收到反馈，感谢提醒");
    });
  });
}

